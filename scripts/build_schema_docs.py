"""Regenerate docs/data-schema.md from leafy_ai.schemas. CI fails if it is stale."""

from pathlib import Path

from leafy_ai.config import load_config
from leafy_ai.schemas import TABLES, schema

INTRO = """# Data schema

Generated by `scripts/build_schema_docs.py` from `src/leafy_ai/schemas.py`; do not edit by hand.
Columns shown for preset `root_disease`, which enables every optional sensor.

- One file per table in a raw export folder: `<table>.csv` or `<table>.parquet`
- `plant_id` is globally unique and starts with `C<cycle>_`, for example `C2_R1S3P07`
- Band columns follow preset `spectral.bands_nm`; LED columns follow `transmission.leds_nm`
  (`led970_*` and `empty970_*` only when 970 nm is enabled)
- `thermal` is required only when `sensors.thermal` is true; `view = root` only when
  `sensors.root_images` is true
- `class = calibration` marks the 60 chlorophyll calibration plants
- Schemas check structure and categories. Saturation, negative counts, drift, repeat CV and
  missing positions are flagged by `leafy_ai.qc`, never rejected or dropped
- Nullable biology columns stay missing when not measured; nothing is imputed
- Ingest: `python scripts/ingest.py --preset <preset> --raw <raw dir> --out data/interim/<name>`
  validates, checks referential integrity, writes immutable Parquet plus `manifest.json`
  (SHA-256 of every source and output) and a QC report in `reports/qc/<name>/`
"""


def describe(column) -> str:
    checks = "; ".join(str(c.error or c.name) for c in column.checks) or ""
    return checks.replace("|", "/")


def render() -> str:
    cfg = load_config("root_disease")
    parts = [INTRO]
    for table in TABLES:
        s = schema(table, cfg)
        parts.append(f"\n## {table}\n")
        if s.unique:
            parts.append(f"Unique key: `{', '.join(s.unique)}`\n")
        for check in s.checks:
            parts.append(f"- Table rule: {check.error}")
        parts.append("\n| Column | Type | Nullable | Checks |\n|---|---|---|---|")
        for name, column in s.columns.items():
            nullable = "yes" if column.nullable else "no"
            parts.append(f"| `{name}` | {column.dtype} | {nullable} | {describe(column)} |")
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "docs/data-schema.md"
    target.write_text(render(), encoding="utf-8")
    print(f"Wrote {target}")
