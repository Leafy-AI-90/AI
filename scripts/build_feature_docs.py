"""Regenerate docs/features.md from leafy_ai.registry. CI fails if it is stale."""

from pathlib import Path

from leafy_ai.config import PRESETS, load_config
from leafy_ai.registry import feature_registry

INTRO = """# Features

Generated by `scripts/build_feature_docs.py` from `src/leafy_ai/registry.py`; do not edit by hand.
`leafy_ai.feature_table.build_features` emits these columns, one row per plant/day.

- Reflectance: dark-corrected leaf counts / dark-corrected white tile counts x tile reflectance,
  using mean of start and end references in same session
- Absorbance: LED-off subtracted from LED-on for leaf and empty clip
- Repeats averaged per leaf position; spectral features averaged across positions
- QC-excluded readings left out of averages; `n_readings` and `n_excluded_readings` record counts
- Positional contrasts are NaN unless every configured position was measured that day
- `_delta` needs same plant's first-day (day -1) row, else NaN; `_slope` uses only current and
  earlier days, so no future measurement leaks into a day's features
- Missing inputs stay NaN; nothing is imputed

## Columns per preset

| Preset | Base features | Total columns |
|---|---:|---:|
"""


def table(features) -> str:
    rows = ["| Name | Unit | Sensor | Equation | Reference |", "|---|---|---|---|---|"]
    rows += [
        f"| `{f.name}` | {f.unit} | {f.sensor} | {f.equation} | {f.reference} |" for f in features
    ]
    return "\n".join(rows)


def render() -> str:
    parts = [INTRO.rstrip("\n")]
    for preset in PRESETS:
        reg = feature_registry(load_config(preset))
        parts.append(f"| `{preset}` | {len(reg) // 3} | {len(reg)} |")
    reg = feature_registry(load_config("root_disease"))
    base = [f for f in reg if not f.name.endswith(("_delta", "_slope"))]
    parts.append("\n## Base features (`root_disease`, superset)\n")
    parts.append("`xcc` adds `pos_m710_lesion` and drops `pos_m710_middle`; presets without")
    parts.append("970 nm or thermal omit `w970` and thermal rows.\n")
    parts.append(table(base))
    parts.append("\n## Temporal features\n")
    parts.append("Every base feature `<name>` also appears as:\n")
    parts.append(
        table([f for f in reg if f.name in (f"{base[0].name}_delta", f"{base[0].name}_slope")])
    )
    parts.append("\nwith the same pattern for every other base feature.")
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "docs/features.md"
    target.write_text(render(), encoding="utf-8")
    print(f"Wrote {target}")
